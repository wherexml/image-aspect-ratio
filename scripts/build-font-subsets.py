"""Generate UI font subsets without changing glyph geometry or full-font coverage.

Maintenance only: pip install 'fonttools[woff]==4.60.2', then run this file.
Original fonts and their OFL licenses remain in public/fonts. The normal app build
uses the checked-in generated files and does not require Python.
"""
import hashlib
import json
from pathlib import Path
from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.pens.recordingPen import RecordingPen

ROOT = Path(__file__).resolve().parents[1]
FONTS = ROOT / "public/fonts"
# New Latin UI text is covered automatically. Any other original glyph loads
# from the original font via the complementary unicode-range declaration.
CORE = set(range(0x20, 0x7F)) | {0xA0, 0xA9, 0xB0, 0xB7, 0xD7, 0xF7, 0x2013,
    0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2026, 0x2190, 0x2191,
    0x2192, 0x2193, 0x2194, 0x2212, 0x2215, 0x2248}
SOURCES = [
    ("Bricolage Grotesque", "bricolage-grotesque-latin-85f55a58.woff2", "500 800"),
    ("Instrument Sans", "instrument-sans-latin-6219bc4b.woff2", "400 600"),
    ("JetBrains Mono", "jetbrains-mono-latin-2c32b9b3.woff2", "400 700"),
]

def ranges(values):
    return ",".join(f"U+{value:04X}" for value in sorted(values))

css = ["/* Generated by scripts/build-font-subsets.py. Original glyphs and axes retained. */"]
manifest = []
for family, filename, weight in SOURCES:
    original = TTFont(FONTS / filename, recalcTimestamp=False)
    font = TTFont(FONTS / filename, recalcTimestamp=False)
    options = subset.Options()
    options.layout_features = ["*"]
    options.name_IDs = ["*"]
    options.name_legacy = True
    options.name_languages = ["*"]
    options.notdef_glyph = options.notdef_outline = options.recommended_glyphs = True
    worker = subset.Subsetter(options=options)
    worker.populate(unicodes=CORE)
    worker.subset(font)
    # Verify outlines and advances at the original default variable location.
    old_glyphs, new_glyphs = original.getGlyphSet(), font.getGlyphSet()
    for code, glyph in font.getBestCmap().items():
        before, after = RecordingPen(), RecordingPen()
        old_glyphs[original.getBestCmap()[code]].draw(before)
        new_glyphs[glyph].draw(after)
        assert before.value == after.value and old_glyphs[glyph].width == new_glyphs[glyph].width
    assert original['fvar'].compile(original) == font['fvar'].compile(font)
    import io
    output = io.BytesIO()
    font.save(output)
    raw = output.getvalue()
    digest = hashlib.sha256(raw).hexdigest()
    name = filename.split('-latin-')[0] + '-ui-' + digest[:8] + '.woff2'
    (FONTS / name).write_bytes(raw)
    included = set(font.getBestCmap())
    remaining = set(original.getBestCmap()) - included
    for url, codes in [(f"../public/fonts/{name}?inline", included), (f"/fonts/{filename}", remaining)]:
        css.append(f"@font-face {{\n  font-family: '{family}';\n  font-style: normal;\n  font-weight: {weight};\n  font-display: swap;\n  src: url({url}) format('woff2');\n  unicode-range: {ranges(codes)};\n}}")
    manifest.append({"family":family,"file":name,"sha256":digest,"bytes":len(raw),"original":filename,"includedCodepoints":sorted(included),"fallbackCodepoints":sorted(remaining)})
(ROOT / 'src/font-faces.css').write_text('\n\n'.join(css)+'\n')
(FONTS / 'ui-subsets.json').write_text(json.dumps(manifest,indent=2)+'\n')
print(json.dumps([{k:v for k,v in row.items() if not isinstance(v,list)} for row in manifest],indent=2))
